import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = join(root, "examples", "private-procurement-vercel");
const destination = join(root, "packages", "create-mirror-webmcp", "template", "next");
const excluded = new Set([
  ".next",
  ".npmrc",
  "node_modules",
  "package-lock.json",
  "README.md",
  "lib/procurement-tools.js",
  "tests/webmcp-flow.test.mjs"
]);

async function copyTree(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const sourcePath = join(directory, entry.name);
    const name = relative(source, sourcePath);
    if (excluded.has(name) || excluded.has(entry.name)) continue;
    const targetPath = join(destination, name);
    if (entry.isDirectory()) {
      await mkdir(targetPath, { recursive: true });
      await copyTree(sourcePath);
    } else {
      await mkdir(dirname(targetPath), { recursive: true });
      await cp(sourcePath, targetPath);
    }
  }
}

await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
await copyTree(source);

const sourceManifest = JSON.parse(await readFile(join(source, "package.json"), "utf8"));
delete sourceManifest.dependencies["@mirror/webmcp-secure"];
sourceManifest.name = "__PROJECT_NAME__";
sourceManifest.version = "0.1.0";
await writeFile(join(destination, "package.json"), `${JSON.stringify(sourceManifest, null, 2)}\n`);

const nextConfigPath = join(destination, "next.config.mjs");
const nextConfig = (await readFile(nextConfigPath, "utf8"))
  .replace('  transpilePackages: ["@mirror/webmcp-secure"],\n', "");
await writeFile(nextConfigPath, nextConfig);

await writeFile(join(destination, "README.md"), `# __PROJECT_NAME__

A private-by-default WebMCP procurement reference generated by \`create-mirror-webmcp\`.

## Run locally

\`\`\`sh
npm run check
npm run dev
\`\`\`

Open <http://localhost:4210>. The page runs an ordinary-browser preview through the same manifest and endpoint-backed tools that a native WebMCP caller discovers.

## What is protected

- Buyer requirements enter the website instead of agent chat.
- The agent receives a short-lived, authenticated handle bound to the site, user, session, purpose and permitted tool.
- The seller application receives only the eligible product identifiers, quantity and delivery window. When the Mirror route is configured, the remote seller model receives encrypted ingress and computes on ciphertext.
- Proposal release and acceptance require explicit approval.
- The client boundary audit rejects private SDK, WASM, secrets and private seller-policy data in browser artifacts.

## Before production

Replace \`applicationUserId\` with identity from your server-verified application session. Replace the procurement manifest, dispatcher and release policy for your use case. Set strong \`MIRROR_WEBMCP_HANDLE_KEY\` and \`PROPOSAL_SIGNING_KEY\` secrets in the deployment environment. Configure \`MIRROR_WEBMCP_FHE_URL\` and \`MIRROR_WEBMCP_FHE_TOKEN\` for protected seller inference, or configure the explicit Vercel AI Gateway fallback. Complete your authorization, durable replay storage and CSP review before production.

The seller-model step fails closed without a real configured server route. It does not return a synthetic proposal.

This project is private by default. Generating it does not deploy or publish anything.
`);

console.log(`Synchronized create-mirror-webmcp Next.js template from ${relative(root, source)}.`);
